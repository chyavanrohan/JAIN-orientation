export const getStudentRegistrations = (): StudentRegistration[] => {
  try {
    const data = localStorage.getItem(STORAGE_KEY);
    if (!data) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_SEED_STUDENTS));
      return INITIAL_SEED_STUDENTS;
    }
    const parsed = JSON.parse(data);
    if (!Array.isArray(parsed) || parsed.length < 200) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_SEED_STUDENTS));
      return INITIAL_SEED_STUDENTS;
    }
    return parsed;
  } catch (err) {
    console.error('Error reading student registrations:', err);
    return INITIAL_SEED_STUDENTS;
  }
};

export const addStudentRegistration = (
  student: Omit<StudentRegistration, 'id' | 'registeredAt' | 'status'>
): StudentRegistration => {
  const current = getStudentRegistrations();
  const nextNumber = 1000 + current.length + 1;
  const isLateral = student.admissionType === 'Lateral Entry';
  
  // Extract department short code from program
  let deptCode = 'CS';
  if (student.program.includes('AI') || student.program.includes('Machine')) deptCode = 'AI';
  else if (student.program.includes('Data')) deptCode = 'DS';
  else if (student.program.includes('Aerospace')) deptCode = 'AE';
  else if (student.program.includes('Robotics')) deptCode = 'RO';
  else if (student.program.includes('Electronics') || student.program.includes('ECE')) deptCode = 'EC';
  else if (student.program.includes('Information')) deptCode = 'IS';
  else if (student.program.includes('Cyber')) deptCode = 'CY';
  else if (student.program.includes('Mechanical')) deptCode = 'ME';
  else if (student.program.includes('Civil')) deptCode = 'CV';
  
  const generatedUsn = student.usn || (isLateral 
    ? `1JU25${deptCode}L${String(nextNumber % 100).padStart(2, '0')}`
    : `1JU26${deptCode}${String(nextNumber % 1000).padStart(3, '0')}`);

  const newStudent: StudentRegistration = {
    ...student,
    usn: generatedUsn,
    admissionType: student.admissionType || 'Freshers',
    id: `JAIN-2026-${nextNumber}`,
    registeredAt: new Date().toLocaleString('en-US', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: true,
    }),
    status: 'Confirmed',
    seatNumber: `S-${Math.floor(Math.random() * 80) + 1}`,
  };

  const updated = [newStudent, ...current];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Error saving student registration:', err);
  }

  return newStudent;
};

export const updateStudentStatus = (
  id: string,
  newStatus: 'Confirmed' | 'Checked-In' | 'Pending'
): StudentRegistration[] => {
  const current = getStudentRegistrations();
  const updated = current.map((s) => (s.id === id ? { ...s, status: newStatus } : s));
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Error updating status:', err);
  }
  return updated;
};

export const deleteStudentRegistration = (id: string): StudentRegistration[] => {
  const current = getStudentRegistrations();
  const updated = current.filter((s) => s.id !== id);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Error deleting student:', err);
  }
  return updated;
};

export const resetStudentRegistrations = (): StudentRegistration[] => {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_SEED_STUDENTS));
  } catch (err) {
    console.error('Error resetting registrations:', err);
  }
  return INITIAL_SEED_STUDENTS;
};
